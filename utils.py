"""
utils.py
========
Shared helpers: JSON I/O, directory creation, code extraction from LLM output,
and saving per-sample files to disk for later dynamic-metric measurement.
"""
import os
import re
import json
from pathlib import Path


# ── File / Directory helpers ───────────────────────────────────────────────────

def ensure_dirs(paths: list[str]) -> None:
    for p in paths:
        Path(p).mkdir(parents=True, exist_ok=True)


def save_json(data, filepath: str, indent: int = 2) -> None:
    Path(filepath).parent.mkdir(parents=True, exist_ok=True)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=indent, ensure_ascii=False)


def load_json(filepath: str):
    with open(filepath, "r", encoding="utf-8") as f:
        return json.load(f)


# ── Code extraction ────────────────────────────────────────────────────────────

def _strip_thinking(text: str) -> str:
    """Remove <think>…</think> blocks that Qwen and some other models emit."""
    return re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()


def extract_code(llm_output: str, language: str) -> str:
    """
    Strip thinking blocks and markdown fences from LLM output, return clean code.
    Tries: ```<language>…```, then ```…```, then returns the raw text.
    """
    cleaned = _strip_thinking(llm_output)

    # language-specific fence
    m = re.search(rf"```{re.escape(language)}\s*(.*?)```", cleaned, re.DOTALL | re.IGNORECASE)
    if m:
        return m.group(1).strip()

    # generic fence
    m = re.search(r"```(?:\w+)?\s*(.*?)```", cleaned, re.DOTALL)
    if m:
        return m.group(1).strip()

    return cleaned


def extract_json_from_response(llm_output: str) -> str:
    """Strip markdown JSON fences and return the raw JSON string."""
    m = re.search(r"```json\s*(.*?)```", llm_output, re.DOTALL | re.IGNORECASE)
    if m:
        return m.group(1).strip()
    m = re.search(r"```\s*([\[{].*?[\]}])\s*```", llm_output, re.DOTALL)
    if m:
        return m.group(1).strip()
    # try to find a bare JSON array or object
    m = re.search(r"(\[.*\]|\{.*\})", llm_output, re.DOTALL)
    if m:
        return m.group(1).strip()
    return llm_output.strip()


# ── Per-sample file saving ─────────────────────────────────────────────────────

def _python_runner_script(original_rel: str, optimized_rel: str, inputs_rel: str) -> str:
    return f"""\
#!/usr/bin/env python3
# Auto-generated by the experiment pipeline.
# Run on the target machine: python run.py
import sys, os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', '..', '..')))
from runner.measure_python import measure_file
import json

base = os.path.dirname(os.path.abspath(__file__))
original_results  = measure_file(os.path.join(base, "{original_rel}"),  os.path.join(base, "{inputs_rel}"))
optimized_results = measure_file(os.path.join(base, "{optimized_rel}"), os.path.join(base, "{inputs_rel}"))

out = {{"original": original_results, "optimized": optimized_results}}
print(json.dumps(out, indent=2))

results_file = os.path.join(base, "dynamic_results.json")
with open(results_file, "w") as f:
    json.dump(out, f, indent=2)
print(f"Results saved to {{results_file}}")
"""


def _java_runner_script() -> str:
    return """\
#!/usr/bin/env bash
# Auto-generated by the experiment pipeline.
# Run on the target machine: bash run.sh
# Requires: javac, java, python3 (with runner/measure_java.py accessible)
set -e
DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$DIR/../../../../../.." && pwd)"
python3 "$REPO_ROOT/runner/measure_java.py" "$DIR/original.java" "$DIR/optimized.java" "$DIR/inputs.json" > "$DIR/dynamic_results.json"
echo "Results saved to $DIR/dynamic_results.json"
"""


def save_sample_to_disk(
    *,
    experiment_id: str,
    sample_id: str,
    model_key: str,
    technique: str,
    language: str,
    original_code: str,
    optimized_code: str,
    inputs: list[dict],
    base_dir: str,
) -> dict:
    """
    Write original code, optimized code, inputs.json, and a runner script to disk.
    Returns a dict of absolute paths for inclusion in the JSON result.
    """
    ext = "py" if language == "python" else "java"
    dir_path = os.path.join(base_dir, experiment_id, f"{model_key}_{technique}", sample_id)
    Path(dir_path).mkdir(parents=True, exist_ok=True)

    original_file  = f"original.{ext}"
    optimized_file = f"optimized.{ext}"
    inputs_file    = "inputs.json"
    runner_file    = "run.py" if language == "python" else "run.sh"

    _write(dir_path, original_file,  original_code)
    _write(dir_path, optimized_file, optimized_code)
    save_json(inputs, os.path.join(dir_path, inputs_file))

    if language == "python":
        runner = _python_runner_script(original_file, optimized_file, inputs_file)
    else:
        runner = _java_runner_script()
    _write(dir_path, runner_file, runner)

    return {
        "directory":     dir_path,
        "original_code": os.path.join(dir_path, original_file),
        "optimized_code": os.path.join(dir_path, optimized_file),
        "inputs":        os.path.join(dir_path, inputs_file),
        "runner_script": os.path.join(dir_path, runner_file),
        "dynamic_results": os.path.join(dir_path, "dynamic_results.json"),
    }


def _write(directory: str, filename: str, content: str) -> None:
    with open(os.path.join(directory, filename), "w", encoding="utf-8") as f:
        f.write(content)
